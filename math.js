// Math Object in JavaScript

let a = 10.5;
let b = 20.6;


console.log("Value of a:", a);
console.log("Value of b:", b);

// round the value of the value (11, 21) 
console.log("Round a:", Math.round(a));
console.log("Round b:", Math.round(b));

// floor mean give previous value like (10,20)
console.log("Floor a:", Math.floor(a));
console.log("Floor b:", Math.floor(b));

// ceil mean give next value like (11,21) 
console.log("Ceil a:", Math.ceil(a));
console.log("Ceil b:", Math.ceil(b));
// get maximum and minimum value of a and b (10,20)
console.log("Maximum:", Math.max(a, b));
console.log("Minimum:", Math.min(a, b));

// get random value between 0 and 1
console.log("Random Number:", Math.random());